func TestReceiveAgentHookRecordsActivityAndGeneratesClaudeContext(t *testing.T) {
	t.Parallel()
	require := require.New(t)
	assert := assert.New(t)
	database := dbtest.Open(t)
	worktree := t.TempDir()
	_, err := reposeed.Seed(t.Context(), database, db.RepoIdentity{
		Platform: "github", PlatformHost: "github.com",
		Owner: "acme", Name: "widget",
	})
	require.NoError(err)
	require.NoError(database.InsertWorkspace(t.Context(), &db.Workspace{
		ID:              "ws-agent-hook",
		Platform:        "github",
		PlatformHost:    "github.com",
		RepoOwner:       "acme",
		RepoName:        "widget",
		ItemType:        db.WorkspaceItemTypeIssue,
		ItemNumber:      42,
		GitHeadRef:      "kenn-forge/issue-42",
		WorkspaceBranch: "kenn-forge/issue-42",
		WorktreePath:    worktree,
		TmuxSession:     "kenn-forge-ws-agent-hook",
		Status:          "ready",
	}))
	require.NoError(database.PutWorkspaceLaunchSpec(
		t.Context(), "ws-agent-hook", workspaceLaunchSpecForRequest(
			providerplane.WorkspaceLaunchRequest{
				Repository: providerplane.RepositoryRoute{
					Provider: "github", PlatformHost: "github.com",
					Owner: "acme", Name: "widget",
				},
				ItemType: db.WorkspaceItemTypeIssue, ItemNumber: 42,
				ItemKey: "42", GitHeadRef: "kenn-forge/issue-42",
			},
			time.Now().UTC(),
		),
	))
	require.NoError(os.WriteFile(
		filepath.Join(worktree, "CLAUDE.local.md"),
		[]byte("private user context that must never be forwarded\n"), 0o644,
	))
	root := t.TempDir()
	activity := agentactivity.NewStore(root)
	handler := New(Deps{
		DB:            database,
		Workspaces:    workspace.NewManager(database, t.TempDir()),
		AgentActivity: activity,
	})
	mux := http.NewServeMux()
	api := humago.NewWithPrefix(
		mux, "/api/v1", huma.DefaultConfig("workspace test", "1"),
	)
	handler.Register(api)

	post := func(agent, runtimeKey string, payload map[string]any) *httptest.ResponseRecorder {
		t.Helper()
		body, err := json.Marshal(payload)
		require.NoError(err)
		req := httptest.NewRequestWithContext(t.Context(),
			http.MethodPost, "/api/v1/agent-hooks/"+agent,
			bytes.NewReader(body),
		)
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("X-Kenn-Forge-Runtime-Session-Key", runtimeKey)
		rec := httptest.NewRecorder()
		mux.ServeHTTP(rec, req)
		return rec
	}

	working := post("gemini", "runtime-1", map[string]any{
		"session_id":      "agent-1",
		"cwd":             worktree,
		"hook_event_name": "UserPromptSubmit",
		"transcript_path": "/tmp/agent-transcript.jsonl",
		"permission_mode": "default",
	})
	require.Equal(http.StatusOK, working.Code, working.Body.String())
	snapshot, ok := activity.SnapshotForWorkspace(worktree, []string{"runtime-1"})
	require.True(ok)
	assert.Equal(agentactivity.StateWorking, snapshot.State)

	started := post("claude", "runtime-1", map[string]any{
		"session_id":      "agent-1",
		"cwd":             worktree,
		"hook_event_name": "SessionStart",
		"source":          "startup",
	})
	require.Equal(http.StatusOK, started.Code, started.Body.String())
	type hookResponse struct {
		HookOutput *struct {
			HookSpecificOutput struct {
				HookEventName     string `json:"hookEventName"`
				AdditionalContext string `json:"additionalContext"`
			} `json:"hookSpecificOutput"`
		} `json:"hook_output"`
	}
	var response hookResponse
	require.NoError(json.NewDecoder(started.Body).Decode(&response))
	require.NotNil(response.HookOutput)
	assert.Equal("SessionStart", response.HookOutput.HookSpecificOutput.HookEventName)
	assert.Contains(response.HookOutput.HookSpecificOutput.AdditionalContext, "Workspace ID: ws-agent-hook")
	assert.Contains(response.HookOutput.HookSpecificOutput.AdditionalContext, "Issue: #42")
	assert.NotContains(response.HookOutput.HookSpecificOutput.AdditionalContext, "private user context")
	assert.NotContains(response.HookOutput.HookSpecificOutput.AdditionalContext, "<!-- generated by kenn-forge")

	entries, err := os.ReadDir(root)
	require.NoError(err)
	for _, entry := range entries {
		path := filepath.Join(root, entry.Name())
		require.NoError(os.Remove(path))
		require.NoError(os.Mkdir(path, 0o700))
		require.NoError(os.WriteFile(filepath.Join(path, "blocked"), nil, 0o600))
	}
	for _, event := range []string{"SessionEnd", "SessionStart"} {
		rec := post("claude", "runtime-1", map[string]any{"session_id": "agent-1", "cwd": worktree, "hook_event_name": event})
		if event == "SessionEnd" {
			assert.Equal(http.StatusInternalServerError, rec.Code)
			var problem generated.ProblemError
			require.NoError(json.Unmarshal(rec.Body.Bytes(), &problem))
			assert.Equal(generated.ProblemErrorCodeInternalError, problem.Code)
			require.NotNil(problem.Detail)
			assert.Contains(*problem.Detail, filepath.Clean(root))
			assert.Contains(*problem.Detail, ".json")
		} else {
			require.Equal(http.StatusOK, rec.Code, rec.Body.String())
			var failureResponse hookResponse
			require.NoError(json.Unmarshal(rec.Body.Bytes(), &failureResponse))
			require.NotNil(failureResponse.HookOutput)
			assert.Equal("SessionStart", failureResponse.HookOutput.HookSpecificOutput.HookEventName)
			assert.Contains(failureResponse.HookOutput.HookSpecificOutput.AdditionalContext, "Workspace ID: ws-agent-hook")
			assert.Contains(failureResponse.HookOutput.HookSpecificOutput.AdditionalContext, "Issue: #42")
		}
	}
}

// An agent the terminal's agent runs in the same worktree inherits the
// terminal's runtime key. Its hooks must not replace the terminal's own saved
// conversation, which recovery resumes; /clear, which ends that conversation
// first, still does. An agent without SessionEnd hooks never shows an end,
// so its newest conversation is saved.
func TestAgentHooksKeepTheTerminalsOwnConversation(t *testing.T) {
	t.Parallel()
	require := require.New(t)
	assert := assert.New(t)
	ctx := t.Context()
	database := dbtest.Open(t)
	worktree := t.TempDir()
	require.NoError(database.InsertWorkspace(ctx, &db.Workspace{
		ID: "workspace", Platform: "github", PlatformHost: "github.com",
		RepoOwner: "acme", RepoName: "widget", ItemType: db.WorkspaceItemTypeAdHoc,
		ItemKey: db.AdHocWorkspaceItemKey("work/nested"), GitHeadRef: "work/nested",
		WorkspaceBranch: "work/nested", WorktreePath: worktree, Status: "ready",
	}))
	for _, key := range []string{"terminal", "droid-terminal"} {
		require.NoError(database.UpsertWorkspaceRuntimeSession(ctx, &db.WorkspaceRuntimeSession{
			WorkspaceID: "workspace", SessionKey: key, TargetKey: "worker",
			Label: "Worker", Kind: "agent", Scope: "session", TmuxSession: "forge-" + key,
		}))
	}
	handler := New(Deps{DB: database, AgentActivity: agentactivity.NewStore(t.TempDir())})
	send := func(agent, key string, hook agentactivity.HookEvent) {
		t.Helper()
		hook.CWD = worktree
		_, err := handler.receiveAgentHook(ctx, &receiveAgentHookInput{
			Agent: agent, RuntimeSessionKey: key, Body: hook,
		})
		require.NoError(err)
	}
	saved := func(key string) db.RuntimeConversation {
		t.Helper()
		conversation, ok, err := database.RuntimeSessionConversation(ctx, key)
		require.NoError(err)
		require.True(ok)
		return db.RuntimeConversation{Agent: conversation.Agent, ID: conversation.ID, EndReason: conversation.EndReason}
	}

	send("claude", "terminal", agentactivity.HookEvent{SessionID: "parent", HookEventName: "SessionStart", Source: "startup"})
	send("claude", "terminal", agentactivity.HookEvent{SessionID: "child", HookEventName: "SessionStart", Source: "startup"})
	send("claude", "terminal", agentactivity.HookEvent{SessionID: "child", HookEventName: "Stop"})
	send("codex", "terminal", agentactivity.HookEvent{SessionID: "codex-child", HookEventName: "Stop"})
	send("claude", "terminal", agentactivity.HookEvent{SessionID: "child", HookEventName: "SessionEnd", Reason: "other"})
	assert.Equal(db.RuntimeConversation{Agent: "claude", ID: "parent"}, saved("terminal"),
		"a nested agent leaves the terminal's conversation and its end in place")

	send("claude", "terminal", agentactivity.HookEvent{SessionID: "parent", HookEventName: "SessionEnd", Reason: "clear"})
	assert.Equal("clear", saved("terminal").EndReason)
	send("claude", "terminal", agentactivity.HookEvent{SessionID: "cleared", HookEventName: "SessionStart", Source: "clear"})
	assert.Equal(db.RuntimeConversation{Agent: "claude", ID: "cleared"}, saved("terminal"),
		"/clear replaces the conversation and clears its end")

	// A restart left the saved conversation's report behind. The resumed
	// runtime starts later, so that report does not hold the place of the
	// conversation the resumed agent reports.
	require.NoError(database.RecordWorkspaceRuntimeSession(ctx, &db.WorkspaceRuntimeSession{
		WorkspaceID: "workspace", SessionKey: "terminal", TargetKey: "worker",
		Label: "Worker", Kind: "agent", Scope: "session", TmuxSession: "forge-resumed",
		CreatedAt: time.Now().UTC().Add(time.Hour),
	}))
	send("claude", "terminal", agentactivity.HookEvent{SessionID: "resumed", HookEventName: "SessionStart", Source: "resume"})
	assert.Equal("resumed", saved("terminal").ID)

	send("droid", "droid-terminal", agentactivity.HookEvent{SessionID: "first", HookEventName: "Stop"})
	send("droid", "droid-terminal", agentactivity.HookEvent{SessionID: "second", HookEventName: "Stop"})
	assert.Equal("second", saved("droid-terminal").ID)
}
