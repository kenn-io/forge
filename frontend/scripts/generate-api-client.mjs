import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "yaml";
import { renderModule, schemaConstraints } from "../../scripts/generate-schema-constraints.mjs";

const vpPath = resolve(dirname(fileURLToPath(import.meta.url)), "../../node_modules/vite-plus/bin/vp");

function operationName(operation) {
  if (!operation.operationId) throw new Error("Every API operation must have an operationId");
  return operation.operationId.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase());
}

function writeIndex(outputDir) {
  const exports = ['export * from "./models/index.ts";'];
  for (const entry of readdirSync(outputDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === "models") continue;
    const serviceName = `${entry.name
      .split("-")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("")}Service`;
    exports.push(`export * as ${serviceName} from "./${entry.name}/${entry.name}.ts";`);
  }
  writeFileSync(join(outputDir, "index.ts"), `${exports.sort().join("\n")}\n`);
}

function run(command, args, frontendDir) {
  const result = spawnSync(command, args, { cwd: frontendDir, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} exited ${result.status}`);
}

async function generateClient(frontendDir) {
  const specPath = resolve(frontendDir, "openapi/openapi.yaml");
  const generatedDir = resolve(frontendDir, "src/lib/api/generated");
  if (!existsSync(specPath)) throw new Error(`OpenAPI document does not exist: ${specPath}`);
  mkdirSync(dirname(generatedDir), { recursive: true });
  const stagingDir = mkdtempSync(resolve(frontendDir, "src/lib/api/generated-next-"));

  try {
    const { generate } = await import("orval");
    await generate(
      {
        input: specPath,
        output: {
          clean: true,
          client: "fetch",
          headers: true,
          mode: "tags-split",
          override: {
            fetch: { includeHttpResponseReturnType: false },
            header: () => ["Generated by Orval. Do not edit manually."],
            mutator: {
              name: "orvalFetch",
              path: resolve(frontendDir, "src/lib/api/runtime.ts"),
            },
            operationName,
            useNamedParameters: true,
          },
          schemas: join(stagingDir, "models"),
          target: stagingDir,
          urlEncodeParameters: true,
        },
      },
      frontendDir,
    );
    writeIndex(stagingDir);
    const document = parse(readFileSync(specPath, "utf8"));
    writeFileSync(join(stagingDir, "schema-constraints.ts"), renderModule(schemaConstraints(document)));
    run(process.execPath, [vpPath, "fmt", stagingDir, "--write"], frontendDir);
    rmSync(generatedDir, { recursive: true, force: true });
    renameSync(stagingDir, generatedDir);
  } finally {
    rmSync(stagingDir, { recursive: true, force: true });
  }
}

/** @returns {import("vite").Plugin} */
export function frontendApiClient() {
  let frontendDir;
  let specPath;
  return {
    name: "kenn-forge-frontend-api-client",
    apply: (_config, { isPreview }) => !isPreview && !process.env.VITEST,
    configResolved(config) {
      frontendDir = config.root;
      specPath = resolve(frontendDir, "openapi/openapi.yaml");
    },
    async buildStart() {
      this.addWatchFile(specPath);
      await generateClient(frontendDir);
    },
    async watchChange(id) {
      if (id === specPath) await generateClient(frontendDir);
    },
  };
}
